export type Point = [number, number, number];
export function fighterPose(technique: number, time: number) {
  const s = Math.pow(Math.max(0, Math.sin(time * Math.PI)), 3);
  const p: Point[] = [
    [-0.43, 1.98, 0],
    [-0.66, 1.55, 0.22],
    [-0.38, 2.12, 0.54],
    [0.43, 1.98, 0],
    [0.64, 1.54, 0.2],
    [0.38, 2.1, 0.5],
    [-0.22, 1.15, 0],
    [-0.35, 0.65, 0.14],
    [-0.48, 0.13, 0.44],
    [0.22, 1.15, 0],
    [0.4, 0.62, -0.12],
    [0.56, 0.13, -0.48],
  ];
  if (technique === 0) {
    p[1] = [-0.5, 1.87, 0.22 + 0.56 * s];
    p[2] = [-0.34, 2.08, 0.54 + 1.12 * s];
  }
  if (technique === 1) {
    p[4] = [0.42, 1.84, 0.2 + 0.7 * s];
    p[5] = [0.18, 2.06, 0.5 + 1.25 * s];
  }
  if (technique === 2) {
    p[1] = [-0.76, 1.55 + 0.48 * s, 0.22 + 0.51 * s];
    p[2] = [-0.38 + 0.58 * s, 2.12, 0.54 + 0.62 * s];
  }
  if (technique === 3) {
    p[10] = [0.4 + 0.35 * s, 0.62 + 0.4 * s, -0.12 + 0.55 * s];
    p[11] = [0.56 + 0.7 * s, 0.13 + 0.75 * s, -0.48 + 1.65 * s];
  }
  if (technique === 4) {
    p[10] = [0.4 - 0.2 * s, 0.62 + 1.04 * s, -0.12 + 0.82 * s];
    p[11] = [0.56 - 0.2 * s, 0.13 + 0.8 * s, -0.48 + 0.62 * s];
  }
  if (technique === 5) {
    p[4] = [0.64 - 0.27 * s, 1.54 + 0.5 * s, 0.2 + 0.85 * s];
    p[5] = [0.38 - 0.58 * s, 2.1 + 0.2 * s, 0.5 - 0.18 * s];
  }
  return {
    points: p,
    turn:
      technique === 1
        ? -0.34 * s
        : technique === 3
          ? 0.42 * s
          : technique === 5
            ? -0.2 * s
            : 0.05 * s,
  };
}
